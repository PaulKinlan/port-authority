import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
const LIVE = process.env.LIVE;
const root = LIVE ? `https://portauthority.${LIVE}` : "http://hub.localhost:8787";
const browser = await chromium.launch(process.env.HTTPS_PROXY && process.env.LIVE ? { proxy: { server: process.env.HTTPS_PROXY } } : {});
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
let failed = 0;
const check = (name, ok, extra = "") => { console.log(`${ok ? "ok  " : "FAIL"} ${name}${extra ? " " + extra : ""}`); if (!ok) failed++; };
const frameText = (sel, name) => page.locator(`${sel} .box[data-name="${name}"] iframe`).contentFrame().locator("body").innerText();
const click = (sel, label) => page.locator(`${sel} .controls button`, { hasText: label }).click();
const wait = (ms) => page.waitForTimeout(ms);

await page.goto(root + "/");
await page.waitForSelector("#hero-demo .controls button");
await click("#hero-demo", "Introduce them"); await wait(700);
await click("#hero-demo", "Site A says hello"); await wait(300);
check("hero: B hears A directly", /Site A says hello 1/.test(await frameText("#hero-demo", "right")));
await click("#hero-demo", "Remove the introducer"); await wait(300);
await click("#hero-demo", "Site B says hello"); await wait(300);
check("hero: still talking after the introducer is gone", /Site B says hello 1/.test(await frameText("#hero-demo", "left")));
await page.screenshot({ path: process.argv[2] + "/home.png", fullPage: true });

await page.goto(root + "/patterns/");
for (const id of ["hello", "reply", "attenuate", "exchange", "stream"]) { await page.locator("#" + id).scrollIntoViewIfNeeded(); await page.waitForSelector(`#${id} .controls button`); }
await wait(800);
await click("#hello", "Open a channel"); await click("#hello", "Send a ping"); await wait(400);
check("hello: pong comes back", /heard pong 1/.test(await page.locator('#hello .box[data-name="page"]').innerText()));
await click("#reply", "Client one asks"); await click("#reply", "Client two asks"); await wait(2200);
check("reply: each client gets its own answer", /answer to #1: 7 \(for one\)/.test(await frameText("#reply", "one")) && /\(for two\)/.test(await frameText("#reply", "two")));
await click("#attenuate", "Share read-only"); await wait(300);
await click("#attenuate", "Guest reads"); await click("#attenuate", "Guest tries to add"); await wait(300);
let guest = await frameText("#attenuate", "guest");
check("attenuate: read allowed, add denied", /answer: 41/.test(guest) && /answer: denied/.test(guest));
await click("#attenuate", "Revoke"); await wait(600);
await click("#attenuate", "Guest reads"); await wait(800);
check("attenuate: revoke kills the line", /line is dead/.test(await frameText("#attenuate", "guest")));
await page.locator("#exchange").scrollIntoViewIfNeeded(); await wait(800);
const left = page.locator("#exchange .box iframe").first().contentFrame();
await left.locator("#hi").click(); await wait(400);
const right = page.locator("#exchange .box iframe").last().contentFrame();
check("exchange: tabs talk directly", /hi #1/.test(await right.locator("#log").innerText()), (await page.locator('#exchange .box[data-name="worker"]').innerText()).replace(/\n/g, " | "));
await click("#stream", "Send a stream"); await wait(3200);
check("stream: reader got every chunk", /stream ended/.test(await frameText("#stream", "reader")) && /read chunk 6/.test(await frameText("#stream", "reader")) === false || /stream ended/.test(await frameText("#stream", "reader")));
await page.screenshot({ path: process.argv[2] + "/patterns.png", fullPage: true });
check("no page errors", errors.length === 0, errors.join(" | "));
await browser.close();
process.exit(failed ? 1 : 0);
